function normalizeName(name: string): string {
  return name
    .replace(/^(Rtn\.?\s*|Rtr\.?\s*|PHF\.?\s*|Dr\.?\s*)+/gi, '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Reliably finds a DAC leader's photo by name, email, or designation fallback.
 */
export function findLeaderPhoto(name?: string | null, email?: string | null, id?: string | null): string | null {
  if (email) {
    const normalizedEmail = email.trim().toLowerCase();
    if (EMAIL_TO_PHOTO[normalizedEmail]) {
      return EMAIL_TO_PHOTO[normalizedEmail];
    }
  }

  if (name) {
    const norm = normalizeName(name);
    if (LEADERSHIP_PHOTOS[norm]) {
      return LEADERSHIP_PHOTOS[norm];
    }

    // Try substring/fuzzy match
    for (const [key, photo] of Object.entries(LEADERSHIP_PHOTOS)) {
      const cleanKey = key.replace(/-/g, '');
      const cleanNorm = norm.replace(/-/g, '');
      if (cleanKey === cleanNorm || cleanNorm.includes(cleanKey) || cleanKey.includes(cleanNorm)) {
        return photo;
      }
    }
  }

  if (id && LEADERSHIP_PHOTOS[id]) {
    return LEADERSHIP_PHOTOS[id];
  }

  return null;
}

/**
 * Resolves a DAC leader's photo URL from portal DB edits, cloud uploads, or local assets.
 */
export function resolveLeaderPhotoUrl(
  photoUrl?: string | null,
  name?: string | null,
  email?: string | null,
  id?: string | null
): string {
  if (photoUrl && photoUrl.trim()) {
    const trimmed = photoUrl.trim();
    // Direct cloud / storage uploads
    if (
      trimmed.startsWith('http://') ||
      trimmed.startsWith('https://') ||
      trimmed.startsWith('data:') ||
      trimmed.startsWith('/storage/') ||
      trimmed.startsWith('/uploads/')
    ) {
      return trimmed;
    }
    // Normalize local /leadership/ paths (.jpg/.png/.jpeg -> .webp)
    if (trimmed.startsWith('/leadership/')) {
      return trimmed.replace(/\.(jpg|jpeg|png)$/i, '.webp');
    }
    if (!trimmed.startsWith('/') && trimmed.includes('.')) {
      return `/leadership/${trimmed.replace(/\.(jpg|jpeg|png)$/i, '.webp')}`;
    }
    return trimmed;
  }

  return findLeaderPhoto(name, email, id) || '';
}
